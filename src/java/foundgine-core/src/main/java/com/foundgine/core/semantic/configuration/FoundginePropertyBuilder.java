package com.foundgine.core.semantic.configuration;

import com.foundgine.core.semantic.configuration.ConfigurationDefinitions.ColumnDefinition;

public final class FoundginePropertyBuilder {
    private final ColumnDefinition column;

    FoundginePropertyBuilder(ColumnDefinition column) {
        this.column = column;
    }

    public FoundginePropertyBuilder hasColumnName(String name) {
        if (name == null || name.isBlank()) throw new IllegalArgumentException("Column name is required.");
        column.columnName = name.trim();
        return this;
    }

    public FoundginePropertyBuilder hasMaxLength(int length) {
        if (length <= 0) throw new IllegalArgumentException("Max length must be positive.");
        column.maxLength = length;
        return this;
    }

    /** Sets the exact SQL type used when a migration creates the column, for example {@code "date"} or {@code "char(64)"}. */
    public FoundginePropertyBuilder hasColumnType(String sqlType) {
        if (sqlType == null || sqlType.isBlank()) throw new IllegalArgumentException("Column type is required.");
        column.sqlType = sqlType.trim();
        return this;
    }

    /** Sets precision and scale for decimal columns, for example {@code hasPrecision(10, 2)}. */
    public FoundginePropertyBuilder hasPrecision(int precision, int scale) {
        if (precision <= 0) throw new IllegalArgumentException("Precision must be positive.");
        if (scale < 0 || scale > precision) throw new IllegalArgumentException("Scale must be between 0 and the precision.");
        column.precision = precision;
        column.scale = scale;
        return this;
    }

    /** Sets a trusted SQL default expression, e.g. CURRENT_TIMESTAMP or gen_random_uuid(). */
    public FoundginePropertyBuilder hasDefault(String expression) {
        if (expression == null || expression.isBlank()) throw new IllegalArgumentException("Default expression is required.");
        if (column.identityGeneration != null) throw new IllegalStateException("An identity column cannot also have a default.");
        column.defaultExpression = expression.trim(); return this;
    }

    /** Declares PostgreSQL GENERATED ALWAYS AS IDENTITY. */
    public FoundginePropertyBuilder isIdentityAlways() { return identity("ALWAYS"); }

    /** Declares PostgreSQL GENERATED BY DEFAULT AS IDENTITY. */
    public FoundginePropertyBuilder isIdentityByDefault() { return identity("BY_DEFAULT"); }

    private FoundginePropertyBuilder identity(String generation) {
        if (column.defaultExpression != null) throw new IllegalStateException("An identity column cannot also have a default.");
        column.identityGeneration = generation; return this;
    }

    public FoundginePropertyBuilder isRequired() {
        return isRequired(true);
    }

    public FoundginePropertyBuilder isRequired(boolean required) {
        column.required = required;
        return this;
    }
}
