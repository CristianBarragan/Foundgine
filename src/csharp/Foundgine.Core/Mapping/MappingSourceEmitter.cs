using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Foundgine.Core.Mapping;

/// <summary>
/// Emits <see cref="MappingModel"/>s as plain C# (constructor calls and string literals only: no reflection,
/// no expression trees, no lambdas, no JSON), so a model built once with the fluent API at design time can be
/// shipped as generated metadata and used by AOT/trimmed apps. Every value is emitted exactly as recorded
/// (CLR types stay the recorded strings), so generated and runtime metadata are equal field for field.
/// Output is deterministic (ordinal ordering of models, no timestamps) so a CI step can regenerate and diff it.
/// </summary>
public static class MappingSourceEmitter
{
    public static string Emit(IReadOnlyDictionary<string, MappingModel> models, string ns, string className)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> Foundgine mapping metadata. Do not edit; regenerate. </auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using Foundgine.Core.Mapping;");
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine($"public static class {className}");
        sb.AppendLine("{");
        var names = models.Keys.OrderBy(k => k, StringComparer.Ordinal).ToList();
        foreach (var name in names)
        {
            sb.AppendLine($"    public static MappingModel {name}() => new MappingModel()");
            foreach (var m in models[name].Mappings.OrderBy(x => x.Domain, StringComparer.Ordinal))
                sb.AppendLine($"        .Add({Mapping(m)})");
            sb.AppendLine("    ;");
            sb.AppendLine();
        }
        sb.AppendLine("    public static readonly IReadOnlyDictionary<string, System.Func<MappingModel>> All = new Dictionary<string, System.Func<MappingModel>>");
        sb.AppendLine("    {");
        foreach (var name in names)
            sb.AppendLine($"        [{Str(name)}] = {name},");
        sb.AppendLine("    };");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string Arr<T>(IEnumerable<T> items, Func<T, string> f) => "[" + string.Join(", ", items.Select(f)) + "]";

    private static string Mapping(DomainMapping m) =>
        $"new DomainMapping({Str(m.Domain)}, {Arr(m.Tables, Table)}, {Arr(m.Computed, Str)}, " +
        $"{Arr(m.Scopes, s => $"new ScopeRule({Str(s.Kind)}, {Str(s.Path)}, {Str(s.Claim)})")}, " +
        $"{Arr(m.Relations, r => $"new RelationBinding({Str(r.Path)}, {Str(r.TargetDomain)}, {Str(r.JoinTable)}, {Str(r.LeftColumn)}, {Str(r.RightColumn)})")}, " +
        $"{Str(m.ParentDomain)})";

    private static string Table(TableBinding t) =>
        $"new TableBinding({Str(t.Table)}, TableRole.{t.Role}, {Str(t.KeyColumn)}, {Arr(t.Columns, Column)}, " +
        $"{Str(t.ParentTable)}, {Str(t.ForeignKey)}, {Str(t.ParentKey)}, {Str(t.DiscriminatorColumn)}, {Str(t.DiscriminatorValue)})";

    private static string Column(ColumnBinding c) => $"new ColumnBinding({Str(c.Path)}, {Str(c.Column)}, {Str(c.ClrType)})";

    private static string Str(string? s) => s is null ? "null" :
        "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n").Replace("\t", "\\t") + "\"";
}
